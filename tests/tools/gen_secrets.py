"""Generates config/secrets.h with random ESP-NOW keys (PMK + one LMK per link).

    python3 tests/tools/gen_secrets.py            # refuses to overwrite
    python3 tests/tools/gen_secrets.py --force    # new keys: re-flash ALL devices

The file is git-ignored. Every device must be flashed from the same secrets.h.
"""

import argparse
import secrets
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NAMES = ["UFO_PMK", "UFO_LMK_ILLUMINATION", "UFO_LMK_M5DIAL_1", "UFO_LMK_M5DIAL_2"]


def key() -> str:
    return "{" + ", ".join(f"0x{b:02X}" for b in secrets.token_bytes(16)) + "}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    path = ROOT / "config" / "secrets.h"
    if path.exists() and not args.force:
        raise SystemExit(f"{path} exists (use --force to rotate keys; then re-flash every device)")
    lines = [
        "// Generated by tests/tools/gen_secrets.py - PRIVATE, do not commit.",
        "#pragma once",
        "",
        *[f"#define {n} {key()}" for n in NAMES],
        "",
    ]
    path.write_text("\n".join(lines))
    path.chmod(0o600)
    print(f"wrote {path} - rebuild and flash hub, illumination, m5dial_1 and m5dial_2")


if __name__ == "__main__":
    main()
