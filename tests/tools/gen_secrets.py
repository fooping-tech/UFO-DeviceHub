"""Generates config/secrets.h with random ESP-NOW keys, one key set per UFO system
(PMK + one LMK per hub<->device link).

    python3 tests/tools/gen_secrets.py            # creates the file, or adds missing systems
    python3 tests/tools/gen_secrets.py --force    # new keys for ALL systems: re-flash every device

The file is git-ignored. Every device of a system must be flashed from the same
secrets.h. The systems get independent keys, so a frame of one system can never
be decrypted by the other (docs/multi-system.md).

Existing keys are never changed without --force. A file with the old
single-system names (UFO_PMK, UFO_LMK_*) keeps them; they are read as system 1.
"""

import argparse
import re
import secrets
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SYSTEMS = (1, 2)
LINKS = ["PMK", "LMK_ILLUMINATION", "LMK_M5DIAL_1", "LMK_M5DIAL_2", "LMK_STAFF_REMOTE"]


def key() -> str:
    return "{" + ", ".join(f"0x{b:02X}" for b in secrets.token_bytes(16)) + "}"


def block(n: int) -> list[str]:
    return [f"// system {n}", *[f"#define UFO_S{n}_{link} {key()}" for link in LINKS], ""]


def has_system(text: str, n: int) -> bool:
    if re.search(rf"#define UFO_S{n}_PMK\b", text):
        return True
    return n == 1 and re.search(r"#define UFO_PMK\b", text) is not None  # old single-system file


def has_link(text: str, n: int, link: str) -> bool:
    if re.search(rf"#define UFO_S{n}_{link}\b", text):
        return True
    return n == 1 and re.search(rf"#define UFO_{link}\b", text) is not None  # old single-system file


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true", help="replace every key (re-flash ALL devices)")
    args = ap.parse_args()
    path = ROOT / "config" / "secrets.h"
    old = path.read_text() if path.exists() and not args.force else ""
    missing = [n for n in SYSTEMS if not has_system(old, n)]
    # links added after a system's keys were made (the staff remote, fw 0.6): only those
    added = [(n, link) for n in SYSTEMS if n not in missing for link in LINKS
             if link != "PMK" and not has_link(old, n, link)]
    if not missing and not added:
        raise SystemExit(f"{path} already has keys for systems {SYSTEMS} (use --force to rotate them)")
    if old:
        extra = [f"#define UFO_S{n}_{link} {key()}" for n, link in added]
        if extra:
            extra = ["// keys for devices added later (the existing keys are unchanged)", *extra, ""]
        text = old.rstrip("\n") + "\n\n" + "\n".join(extra + [line for n in missing for line in block(n)])
    else:
        text = "\n".join(
            ["// Generated by tests/tools/gen_secrets.py - PRIVATE, do not commit.", "#pragma once", ""]
            + [line for n in missing for line in block(n)]
        )
    path.write_text(text)
    path.chmod(0o600)
    if missing:
        print(f"wrote {path}: new keys for system(s) {', '.join(map(str, missing))}")
        print("rebuild and flash every device of those systems (hub_sN, illumination_sN, m5dial_1_sN, m5dial_2_sN, "
              "staff_remote_sN)")
    for n, link in added:
        print(f"wrote {path}: added UFO_S{n}_{link} (flash hub_s{n} and that device; the other keys are unchanged)")


if __name__ == "__main__":
    main()
